// Exercises the actual migration and RLS in PostgreSQL (PGlite), without cloud credentials.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const { PGlite } = await import(process.env.PGLITE_MODULE_PATH || '@electric-sql/pglite');
const db = new PGlite();
const a='aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa', b='bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb';
const doc=JSON.stringify({format:1,state:{cards:[],pomos:2}});
let checks=0;
const rejects=async(query,args=[])=>{await assert.rejects(()=>db.query(query,args));checks++};
try {
 await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
 create schema auth; create table auth.users(id uuid primary key);
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 grant usage on schema auth to anon,authenticated,service_role;
 insert into auth.users values('${a}'),('${b}');`);
 await db.exec(fs.readFileSync('supabase/migrations/202610090001_prepdesk.sql','utf8'));
 await db.exec(`set role authenticated; set request.jwt.claim.sub='${a}'`);
 assert.equal((await db.query('select public.save_progress(0,$1::jsonb) as revision',[doc])).rows[0].revision,1);checks++;
 await rejects('select public.save_progress(0,$1::jsonb)',[doc]);
 await rejects('select public.save_progress(null,$1::jsonb)',[doc]);
 await rejects('select public.save_progress(1,null)');
 assert.equal((await db.query('select public.save_progress(1,$1::jsonb) as revision',[doc])).rows[0].revision,2);checks++;
 assert.equal((await db.query('select * from public.progress')).rows.length,1);checks++;
 await rejects(`insert into public.progress(user_id,document) values('${b}',$1::jsonb)`,[doc]);
 await rejects(`update public.progress set revision=99`);
 await db.exec(`set request.jwt.claim.sub='${b}'`);
 assert.equal((await db.query('select * from public.progress')).rows.length,0);checks++;
 await rejects('select public.publish_content($1::jsonb)',[JSON.stringify({format:1,questions:[]})]);
 await rejects(`select public.consume_budget('${a}','assess',30)`);
 await db.exec('set role anon');
 await rejects('select * from public.progress');
 await rejects('select public.save_progress(0,$1::jsonb)',[doc]);
 await db.exec('reset role');
 const pack={format:1,questions:[{id:'q1',version:1,q:'Original question'}],sources:[],resources:[]};
 await db.query('select public.publish_content($1::jsonb)',[JSON.stringify(pack)]);
 await db.exec('set role anon');
 assert.equal((await db.query('select * from public.content_releases')).rows.length,1);checks++;
 await rejects('select * from public.interview_questions');
 await db.exec('reset role');
 await db.query('select public.publish_content($1::jsonb)',[JSON.stringify({...pack,questions:[{id:'q1',version:2,q:'Updated question'}]})]);
 assert.equal((await db.query('select count(*)::int as n from public.content_releases where active')).rows[0].n,1);checks++;
 await rejects('select public.publish_content($1::jsonb)',[JSON.stringify(pack)]);
 assert.equal((await db.query('select document from public.interview_questions')).rows[0].document.version,2);checks++;
 assert.equal((await db.query(`select public.consume_budget('${a}','assess',1) as allowed`)).rows[0].allowed,true);checks++;
 assert.equal((await db.query(`select public.consume_budget('${a}','assess',1) as allowed`)).rows[0].allowed,false);checks++;
 await db.exec('set role service_role');
 assert.equal((await db.query('select * from public.interview_questions')).rows.length,1);checks++;
 await db.exec(`insert into public.code_jobs(token,user_id) values ('job','${a}');`);
 await db.exec(`reset role; delete from auth.users where id='${a}';`);
 assert.equal((await db.query('select * from public.progress')).rows.length,0);checks++;
 assert.equal((await db.query('select * from public.code_jobs')).rows.length,0);checks++;
 assert.equal((await db.query('select * from public.service_usage')).rows.length,0);checks++;
 console.log(`Passed ${checks} PostgreSQL checks: owner isolation, permissions, revision conflicts, quotas, atomic publication, account cascade.`);
} finally { await db.close(); }
